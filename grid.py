"""
Generate a 2-object relevance grid: one relevance YAML per (rho_A, rho_B) cell plus a sweep file.

    python -m relevance.grid --task close_drawer --objects ref:drawer robot --labels Drawer Robot
    python -m relevance.grid --task close_drawer --objects ref:drawer robot --levels 0 0.25 0.5 0.75 1

Writes configs/relevance/<task>/grid_<A>_<B>.yaml (A, B = relevance x 100, e.g. grid_050_100) and
configs/sweeps/grid_<task>.yaml. Every other object gets --default-relevance (0 = not considered
in training); evaluation still scores damage on every object. Then:

    python -m relevance.sweep --config relevance/configs/sweeps/grid_<task>.yaml
    python -m relevance.plot_grid --config relevance/configs/sweeps/grid_<task>.yaml
"""

from __future__ import annotations

import argparse
import itertools
import os

import yaml

from relevance.weights import CONFIG_DIR

SWEEP_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), "configs", "sweeps")


def cell_name(levels) -> str:
    return "grid_" + "_".join(f"{round(v * 100):03d}" for v in levels)


def parse_args(argv=None):
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--task", required=True)
    p.add_argument("--objects", nargs=2, required=True, help="two relevance keys, e.g. ref:drawer robot")
    p.add_argument("--labels", nargs=2, default=None, help="axis labels for the plot")
    p.add_argument("--levels", nargs="+", type=float, default=[0.0, 0.5, 1.0])
    p.add_argument("--penalty-weight", type=float, default=1.0)
    p.add_argument("--default-relevance", type=float, default=0.0)
    p.add_argument("--damage-mode", default="sum", choices=["sum", "min"])
    p.add_argument("--seeds", nargs="+", type=int, default=[0])
    p.add_argument("--horizon", type=int, default=200)
    p.add_argument("--total-timesteps", type=int, default=300_000)
    p.add_argument("--n-envs", type=int, default=4)
    p.add_argument("--eval-episodes", type=int, default=20)
    return p.parse_args(argv)


def main(argv=None):
    args = parse_args(argv)
    labels = args.labels or args.objects
    task_dir = os.path.join(CONFIG_DIR, args.task)
    os.makedirs(task_dir, exist_ok=True)

    names = []
    for levels in itertools.product(args.levels, repeat=2):
        name = cell_name(levels)
        names.append(name)
        cfg = {
            "task": args.task,
            "penalty_weight": args.penalty_weight,
            "default_relevance": args.default_relevance,
            "damage_mode": args.damage_mode,
            "grid": {"objects": list(args.objects), "labels": list(labels), "levels": list(levels)},
            "relevance": dict(zip(args.objects, levels)),
        }
        with open(os.path.join(task_dir, f"{name}.yaml"), "w") as f:
            f.write(f"# Grid cell: {labels[0]} = {levels[0]:g}, {labels[1]} = {levels[1]:g}\n")
            yaml.safe_dump(cfg, f, sort_keys=False)

    sweep = {
        "out_dir": f"runs/grid_{args.task}",
        "env": {"horizon": args.horizon, "obs_keys": ["robot0_proprio", "object-state", "task-state"]},
        "ppo": {"total_timesteps": args.total_timesteps, "n_envs": args.n_envs, "n_steps": 512,
                "batch_size": 512, "checkpoint_every": 100_000, "device": "cpu"},
        "eval": {"episodes": args.eval_episodes},
        "sweep": {"tasks": [args.task], "relevance": names, "seeds": list(args.seeds)},
    }
    os.makedirs(SWEEP_DIR, exist_ok=True)
    sweep_path = os.path.join(SWEEP_DIR, f"grid_{args.task}.yaml")
    with open(sweep_path, "w") as f:
        f.write(f"# {len(args.levels)}x{len(args.levels)} grid over {labels[0]} x {labels[1]} "
                f"(generated by relevance.grid)\n")
        yaml.safe_dump(sweep, f, sort_keys=False)

    print(f"[grid] wrote {len(names)} configs to {task_dir}")
    print(f"[grid] wrote {sweep_path} ({len(names) * len(args.seeds)} runs)")


if __name__ == "__main__":
    main()
